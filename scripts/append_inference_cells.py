        "    @classmethod\n",
        "    def extract(cls, payload: Dict[str, Any]) -> pd.DataFrame:\n",
        "        ref_date = datetime(2026, 10, 24)\n",
        "\n",
        "        # 1. MAESTRO_CLIENTES\n",
        "        clte = payload.get('maestro_clientes', {})\n",

        "        'GASTO_PROMEDIO_TC', 'CUOTA_DIFERIDOS_TC', 'VIAJES_EXTERIOR_TC', 'MONTO_POLIZAS_VIGENTES',\n",
        "        'MONTO_ACUM_METAS', 'CUMPLIO_META_HIST', 'INGRESOS_EXTRA_OCR', 'GASTOS_OCULTOS_OCR',\n",
